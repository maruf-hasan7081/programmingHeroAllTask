// this part is incremental loop

for (let i=0; i<=10; i++){
    console.log(i);
}

//even
for(let i=0; i<10 ; i+=2) // i+=2 means i=i+2 also calle shorthand operator
{
    console.log(i);
}
// odd
for(let i=1; i<10 ; i+=2) // i+=2 means i=i+2 also calle shorthand operator
{
    console.log(i);
}



// this part is decremental loop
for(let i=20; i>=0; i--){
    console.log(i);
}


